// Build step: copies the Latin font files into public/fonts and writes the two @font-face sheets:
// src/design/fonts.css (Inter Tight, in the page CSS) and public/fonts/late.css (after first paint).
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { EARLY_FONTS, fontFaceCss, LATE_FONTS } from "../src/design/fonts.ts";

const web = fileURLToPath(new URL("..", import.meta.url));
const require = createRequire(join(web, "package.json"));
const out = join(web, "public", "fonts");
mkdirSync(out, { recursive: true });
for (const f of [...EARLY_FONTS, ...LATE_FONTS]) {
  const dir = dirname(require.resolve(`@fontsource/${f.pkg}/package.json`));
  copyFileSync(join(dir, "files", f.file), join(out, f.file));
}
const header = "/* Generated by scripts/fonts.mjs from src/design/fonts.ts. Do not edit. */\n";
writeFileSync(join(web, "src", "design", "fonts.css"), header + fontFaceCss(EARLY_FONTS) + "\n");
writeFileSync(join(out, "late.css"), header + fontFaceCss(LATE_FONTS) + "\n");
console.log(`fonts: ${EARLY_FONTS.length} early, ${LATE_FONTS.length} late (Latin only)`);
