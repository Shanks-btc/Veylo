// docs/WALLETS.md, rendered from the committed lock (src/wallet/wallets.lock.json) and the hand
// review next to it (wallets.review.json), so the document can never disagree with what the app
// serves. A test renders it again and compares. Plain text out; no network.

const KIND = {
  app: "mobile or desktop app",
  web: "web wallet",
  extension: "browser extension",
  hardware: "hardware wallet",
  multisig: "multisig (a contract account)",
  relay: "relay (WalletConnect)",
  evm: "Ethereum wallet",
  developer: "developer tool",
  unknown: "unknown",
};

const short = (hash) => `${hash.slice(0, 12)}…${hash.slice(-6)}`;

export function renderWalletsDoc(lock, review) {
  const wallets = lock.wallets;
  const enabled = wallets.filter((w) => w.enabled);
  const excluded = wallets.filter((w) => !w.enabled);
  const lines = [];
  const push = (...l) => lines.push(...l);

  push(
    "# NEAR wallets in Veylo",
    "",
    "Generated by `node apps/web/scripts/wallets-doc.mjs` from `apps/web/src/wallet/wallets.lock.json` and `wallets.review.json`. A test fails if this file and those two disagree.",
    "",
    "## Where the list comes from",
    "",
    `- The near-connect wallet manifest: <${lock.manifest.url}>, version ${lock.manifest.version}, fetched ${lock.manifest.fetchedAt}.`,
    "- It lists " +
      wallets.length +
      " wallets. Veylo enables " +
      enabled.length +
      " of them and excludes " +
      excluded.length +
      ", each with the reason below.",
    '- The wallet picker shows HOT Wallet and Meteor first, then the others. On a phone, wallets with an app come before browser extensions. A "Need a wallet? Get one" list links to each wallet\'s own page.',
    "",
    "## The rules a wallet must pass",
    "",
    "1. **It signs a message.** The manifest declares `signMessage`, and the wallet's code handles NEP-413 `signMessage` with our fields (message, nonce, recipient). The counts in the table below are how many times the executor's code names each field.",
    "2. **It needs nothing risky.** No hardware (USB, HID, Bluetooth) and no WalletConnect relay permission. Addresses a manifest lets a wallet open that point at the developer's own computer (localhost, *.localhost, *.local) are dropped from the lock: a production bridge never permits opening one.",
    "3. **Every host it talks to is reviewed.** The hosts come from reading the executor's code (file, line and column below). Only reviewed hosts are added to that wallet's own page on the wallet origin; the app's own content-security policy is never loosened.",
    "4. **Its code is pinned.** Each executor is served from the wallet origin under a name that carries its SHA-256. A test recomputes the hash of every file and fails if a served file differs from its pin.",
    "5. **The app checks the same way for every wallet.** Whatever wallet signs, the app verifies the signature over the exact bytes, the key and the account itself, every time, and the browser gates (quote signature, payee list, key, amount, time) are unchanged.",
    "",
    "## Enabled wallets",
    "",
    "| Wallet | Kind | Version | Executor SHA-256 | Why it passed |",
    "| --- | --- | --- | --- | --- |",
  );
  for (const w of enabled) {
    const r = review.wallets[w.id] ?? {};
    push(
      `| ${w.name} (\`${w.id}\`) | ${KIND[w.kind] ?? w.kind} | ${w.version} | \`${short(w.executor.sha256)}\` | ${r.reason ?? w.reason} |`,
    );
  }
  push(
    "",
    "Full hashes and the file each one is served from are in `apps/web/src/wallet/wallets.lock.json`.",
    "",
    "## Excluded wallets",
    "",
    "| Wallet | Kind | Why it is not enabled |",
    "| --- | --- | --- |",
  );
  for (const w of excluded) {
    const r = review.wallets[w.id] ?? {};
    push(`| ${w.name} (\`${w.id}\`) | ${KIND[w.kind] ?? w.kind} | ${r.reason ?? w.reason} |`);
  }

  push(
    "",
    "## Hosts, from the code",
    "",
    "Each host is an address the wallet's executor names. `file:line:col` points into the pinned executor file under `apps/web/public/wallets/`. Verdicts: **connect** (the wallet may fetch from it), **img** (images only), **frame** (may be framed), **ignored** (named in the code but never fetched: a link opened in a new window, a library comment, a font that falls back to system fonts).",
    "",
  );
  for (const w of enabled) {
    push(
      `### ${w.name}`,
      "",
      `Executor: \`${w.executor.file}\` (${w.executor.bytes} bytes).`,
      "",
      "| Host | Verdict | Where | Note |",
      "| --- | --- | --- | --- |",
    );
    for (const h of w.hosts) {
      push(
        `| ${h.origin} | ${h.verdict} | ${w.executor.file}:${h.line}:${h.col} | ${h.note || ""} |`,
      );
    }
    push("");
  }

  push(
    "## NEP-413 evidence",
    "",
    "| Wallet | `signMessage` mentions | nonce mentions | recipient mentions |",
    "| --- | --- | --- | --- |",
  );
  for (const w of enabled)
    push(`| ${w.name} | ${w.nep413.signMessage} | ${w.nep413.nonce} | ${w.nep413.recipient} |`);

  push(
    "",
    "## What has and has not been tested",
    "",
    "- **Read and tested on fixtures:** every enabled wallet's executor was read for hosts and for its `signMessage` handling, and each one has fixture tests in `apps/web/src/wallet/wallets-flows.test.ts` for sign-in, payee approval and payout signing, plus a test that the app refuses a signature over different bytes.",
    "- **Tested with the real wallet:** Meteor only (spike S-A2, 2026-11-10). Its executor stays pinned to the file that was tested, because the manifest's latest file moved afterwards.",
    "- **Not yet tested live:** the other enabled wallets. A live test of each (sign in, approve a payee, sign a payout with a tiny amount) needs the founder, because it uses a real wallet.",
    "",
    "## Keeping the list current",
    "",
    "`pnpm wallets:refresh` fetches the manifest again and prints what changed: new wallets, executor hashes that moved, and hosts that appeared or went away. It writes nothing unless it is run with `--write` and the founder has approved with `VEYLO_WALLET_PINS_APPROVED=1`. A changed executor is a reviewed change, not an automatic one.",
    "",
  );
  return lines.join("\n");
}
