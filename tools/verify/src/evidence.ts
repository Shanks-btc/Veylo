// docs/EVIDENCE.md: generated, deterministic, and re-checked by `pnpm verify` against public RPC
// with no keys (ARCHITECTURE §11.5). The table format is parsed back by parseEvidence, so the two
// must change together.
import { formatFixed } from "@veylo/core";
import { txExplorerUrl, type ExplorerChain } from "@veylo/chains";
import { PHASE2_NOTES, PHASE2_ROWS, type Phase2Row } from "./phase2-evidence.js";

export type EvidenceRow = Phase2Row;

const TOKENS: Record<string, Record<string, string>> = {
  base: { USDC: "0x833589fcd6edb6e08f4c7c32d4f71b54bda02913" },
  arb: { USDC: "0xaf88d065e77c8cc2239327c5edb3a432268e5831" },
  bsc: { USDT: "0x55d398326f99059ff775485246999027b3197955" },
};
const CHAIN_NAMES: Record<EvidenceRow["chain"], string> = {
  near: "NEAR",
  base: "Base",
  arb: "Arbitrum",
  bsc: "BNB Smart Chain",
  sol: "Solana",
};
const HEADER =
  "| # | Date (UTC) | Event | Chain | Transaction | Look-up account / recipient | Amount | Explorer | Source |";

const cell = (text: string) => text.replaceAll("|", "\\|");

function table(rows: readonly EvidenceRow[]): string[] {
  const sorted = [...rows].sort((a, b) =>
    a.date === b.date
      ? (a.chain + a.tx).localeCompare(b.chain + b.tx)
      : a.date.localeCompare(b.date),
  );
  return [
    HEADER,
    "|---|---|---|---|---|---|---|---|---|",
    ...sorted.map((r, i) =>
      [
        "",
        String(i + 1),
        r.date,
        cell(r.event),
        CHAIN_NAMES[r.chain],
        `\`${r.tx}\``,
        `\`${r.party}\``,
        r.amount ? `${formatFixed(r.amount.units, r.amount.decimals)} ${r.amount.symbol}` : "—",
        txExplorerUrl(r.chain as ExplorerChain, r.tx) ?? "—",
        cell(r.source),
        "",
      ]
        .join(" | ")
        .trim(),
    ),
  ];
}

/** The whole file. The same rows always give the same bytes: no generation time, sorted rows. */
export function renderEvidence(productRows: readonly EvidenceRow[]): string {
  return [
    "# EVIDENCE",
    "",
    "Generated by `pnpm evidence:generate`. Do not edit by hand. `pnpm verify` re-checks every row below against public RPC, with no keys.",
    "",
    "This file lists transactions and nothing more. It makes no claim beyond the rows.",
    "",
    "## Section 1: Product payouts",
    "",
    "Live, reconciled, successful payouts and completed treasury events recorded by Veylo itself. Simulated records are never included.",
    "",
    ...(productRows.length === 0 ? ["None yet."] : table(productRows)),
    "",
    "## Section 2: Phase 2 verification transactions",
    "",
    "Real mainnet transactions from the Phase 2 verification spikes (T5 funding, C2, batch, T5b, T5d, S-E), copied as data from `verification/results/`. These were made by test scripts, not by the product.",
    "",
    ...table(PHASE2_ROWS),
    "",
    "Not re-checkable:",
    "",
    ...PHASE2_NOTES.map((n) => `- ${n}`),
    "",
  ].join("\n");
}

const CHAINS: Record<string, EvidenceRow["chain"]> = {
  NEAR: "near",
  Base: "base",
  Arbitrum: "arb",
  "BNB Smart Chain": "bsc",
  Solana: "sol",
};
const DECIMALS: Record<string, 6 | 18> = { USDC: 6, USDT: 18 };

/** Reads the rows back. Throws on a malformed row rather than skip it. */
export function parseEvidence(markdown: string): EvidenceRow[] {
  const rows: EvidenceRow[] = [];
  for (const line of markdown.split("\n")) {
    if (!/^\| \d+ \|/.test(line)) continue;
    const cells = line
      .slice(2, -2)
      .split(/ (?<!\\)\| /)
      .map((c) => c.replaceAll("\\|", "|"));
    if (cells.length !== 9) throw new Error(`malformed evidence row: ${line.slice(0, 60)}`);
    const [, date, event, chainName, tx, party, amountText, , source] = cells as string[];
    const chain = CHAINS[chainName as string];
    const strip = (s: string) => s.replace(/^`|`$/g, "");
    if (!chain) throw new Error(`unknown chain in evidence row: ${chainName}`);
    let amount: EvidenceRow["amount"];
    if (amountText !== "—") {
      const m = /^(\d+)\.(\d+) (USDC|USDT)$/.exec(amountText as string);
      const decimals = m && DECIMALS[m[3] as string];
      if (!m || !decimals || (m[2] as string).length !== decimals) {
        throw new Error(`malformed amount in evidence row: ${amountText}`);
      }
      amount = {
        units: BigInt(`${m[1]}${m[2]}`),
        symbol: m[3] as "USDC" | "USDT",
        decimals,
      };
    }
    rows.push({
      date: date as string,
      event: event as string,
      chain,
      tx: strip(tx as string),
      party: strip(party as string),
      ...(amount ? { amount } : {}),
      source: source as string,
    });
  }
  return rows;
}

export type RowResult = { status: "PASS" | "FAIL" | "SKIPPED"; detail: string };
export type EvidenceRpcs = { near: string; base: string; arb: string; bsc: string; sol: string };

/** Documented public endpoints, all keyless. Each can be overridden (see .env.example). */
export const DEFAULT_EVIDENCE_RPCS: EvidenceRpcs = {
  near: "https://archival-rpc.mainnet.fastnear.com",
  base: "https://mainnet.base.org",
  arb: "https://arb1.arbitrum.io/rpc",
  bsc: "https://bsc-dataseed.bnbchain.org",
  sol: "https://api.mainnet-beta.solana.com",
};

const TRANSFER = "0xddf252ad1be2c89b69c2b068fc378daa952ba7f163c4a11628f55a4df523b3ef";
class NetworkError extends Error {}

async function rpc(fetch: typeof globalThis.fetch, url: string, method: string, params: unknown) {
  let res: Response;
  try {
    res = await fetch(url, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }),
      signal: AbortSignal.timeout(20_000),
    });
  } catch {
    throw new NetworkError("network unavailable");
  }
  if (res.status === 429 || res.status >= 500) throw new NetworkError(`HTTP ${res.status}`);
  let body: { result?: any; error?: any };
  try {
    body = (await res.json()) as { result?: any; error?: any };
  } catch {
    throw new NetworkError("unreadable response");
  }
  if (!body || typeof body !== "object") throw new NetworkError("unreadable response");
  // A JSON-RPC error is the node failing to answer (rate limit, pruned history, overload), not
  // evidence about the transaction, so it's SKIPPED. The only exception is NEAR's
  // UNKNOWN_TRANSACTION, a definitive "no such transaction" from an archival node.
  if (body.error && !(method === "tx" && body.error?.cause?.name === "UNKNOWN_TRANSACTION")) {
    throw new NetworkError(
      `RPC error ${String(body.error?.cause?.name ?? body.error?.code ?? "")}`.trim(),
    );
  }
  return body;
}

/**
 * One row against public RPC. An RPC error, timeout, 429, 5xx or unreadable answer is SKIPPED
 * (network), never PASS. FAIL only when the RPC returns definitive data that contradicts the row.
 */
export async function checkRow(
  row: EvidenceRow,
  rpcs: EvidenceRpcs,
  fetch: typeof globalThis.fetch,
): Promise<RowResult> {
  try {
    if (row.chain === "near") {
      const r = await rpc(fetch, rpcs.near, "tx", {
        tx_hash: row.tx,
        sender_account_id: row.party,
        wait_until: "NONE",
      });
      if (r.error?.cause?.name === "UNKNOWN_TRANSACTION")
        return { status: "FAIL", detail: "UNKNOWN_TRANSACTION: no such transaction" };
      const status = r.result?.status;
      if (!status || typeof status !== "object") throw new NetworkError("unexpected response");
      if ("Failure" in status) return { status: "FAIL", detail: "transaction failed" };
      if (r.result.final_execution_status !== "FINAL")
        throw new NetworkError("node reports the transaction not final yet");
      if ("SuccessValue" in status || "SuccessReceiptId" in status)
        return { status: "PASS", detail: "final and successful" };
      throw new NetworkError("unexpected response");
    }
    if (row.chain === "sol") {
      const r = await rpc(fetch, rpcs.sol, "getTransaction", [
        row.tx,
        { encoding: "jsonParsed", maxSupportedTransactionVersion: 0 },
      ]);
      if (!r.result) return { status: "FAIL", detail: "transaction not found" };
      if (r.result.meta?.err !== null) return { status: "FAIL", detail: "transaction failed" };
      if (!row.amount) return { status: "PASS", detail: "confirmed" };
      // The recipient's token balance must have risen by exactly the amount.
      const owned = (list: { owner?: string; uiTokenAmount: { amount: string } }[] = []) =>
        list
          .filter((b) => b.owner === row.party)
          .reduce((sum, b) => sum + BigInt(b.uiTokenAmount.amount), 0n);
      const gained = owned(r.result.meta.postTokenBalances) - owned(r.result.meta.preTokenBalances);
      return gained === row.amount.units
        ? { status: "PASS", detail: "recipient received the exact amount" }
        : { status: "FAIL", detail: "recipient didn't receive that amount" };
    }
    const r = await rpc(fetch, rpcs[row.chain], "eth_getTransactionReceipt", [row.tx]);
    if (!r.result) return { status: "FAIL", detail: "receipt not found" };
    if (r.result.status !== "0x1") return { status: "FAIL", detail: "transaction reverted" };
    if (!row.amount) return { status: "FAIL", detail: "no amount to check" };
    const token = TOKENS[row.chain]?.[row.amount.symbol];
    const to = `0x${row.party.slice(2).toLowerCase().padStart(64, "0")}`;
    const match = (r.result.logs as { address: string; topics: string[]; data: string }[]).some(
      (l) =>
        l.address.toLowerCase() === token &&
        l.topics[0] === TRANSFER &&
        l.topics[2]?.toLowerCase() === to &&
        BigInt(l.data) === row.amount?.units,
    );
    return match
      ? { status: "PASS", detail: `${row.amount.symbol} transfer to the recipient, exact amount` }
      : { status: "FAIL", detail: "no transfer of that amount to that recipient" };
  } catch (err) {
    if (err instanceof NetworkError)
      return { status: "SKIPPED", detail: `network: ${err.message}` };
    // A shape we can't read isn't a contradiction either.
    return { status: "SKIPPED", detail: "network: unexpected response" };
  }
}
